  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_pr_items_company_id (company_id),
  INDEX idx_pr_items_req_id (requisition_id),
  INDEX idx_pr_items_material_id (raw_material_id),
  FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE,
