-- SmartBilling Migration 009: Plastic Recycling Phase 6 Procurement, Vendor & Purchase Intelligence
-- Purpose: Add specialized ERP tables for Purchase Requisitions, Supplier Quotations,
--          Purchase Orders, Purchase Deliveries, Supplier Performance, Rate Intelligence, and MRP.
-- Safety: IDEMPOTENT, NON-DESTRUCTIVE, NO DROPS, NO MODIFICATION OF EXISTING PRODUCTION DATA

-- 1. Purchase Requisitions Table
CREATE TABLE IF NOT EXISTS plastic_purchase_requisitions (
  id INT AUTO_INCREMENT PRIMARY KEY,
  company_id INT NOT NULL,
  pr_no VARCHAR(50) NOT NULL,
  request_date DATE NOT NULL,
  requester_name VARCHAR(150) NOT NULL,
  department VARCHAR(100) NOT NULL DEFAULT 'Procurement',
  priority VARCHAR(20) NOT NULL DEFAULT 'MEDIUM',
  required_date DATE NULL,
  notes TEXT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
  approved_by INT NULL,
  approved_at DATETIME NULL,
  rejection_reason TEXT NULL,
  created_by INT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY unique_company_pr_no (company_id, pr_no),
  INDEX idx_pr_company_id (company_id),
  INDEX idx_pr_status (status),
  INDEX idx_pr_priority (priority),
  INDEX idx_pr_request_date (request_date),
  FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE,
  FOREIGN KEY (approved_by) REFERENCES admins(id) ON DELETE SET NULL,
  FOREIGN KEY (created_by) REFERENCES admins(id) ON DELETE SET NULL
);

-- 2. Purchase Requisition Items Table
CREATE TABLE IF NOT EXISTS plastic_purchase_requisition_items (
